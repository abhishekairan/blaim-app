// Converts portraits in docs/img/people/ into web images and regenerates src/components/photos.data.ts.
//   npm run photos             convert every photo, report unmatched files and who still has no photo
//   npm run photos -- --list   only print the file name expected for each person
//
// Name each source file after the person's slug, e.g. "iype-cherian.jpg" for "Dr. Iype Cherian"
// (any of .jpg .jpeg .png .webp). Outputs, cropped from the upper part of the photo to keep the face:
//   public/assets/people/<slug>-160.webp   160x160, card circle
//   public/assets/people/<slug>-600.webp   480x600, hover card portrait
// Requires ffmpeg on PATH.
import { spawnSync } from "node:child_process";
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { extname, join } from "node:path";
import { committees, guests, speakersByTheme } from "../src/data/conference.ts";
import { personSlug } from "../src/lib/people.ts";

const SOURCE = "docs/img/people";
const OUT = "public/assets/people";
const DATA = "src/components/photos.data.ts";
const EXTENSIONS = new Set([".jpg", ".jpeg", ".png", ".webp"]);

const people = new Map<string, string>(); // slug -> display name
for (const p of [...guests, ...speakersByTheme.flat(), ...committees.flatMap((c) => c.people)]) {
  people.set(personSlug(p.name), p.name);
}

if (process.argv.includes("--list")) {
  for (const [slug, name] of [...people].sort()) console.log(`${slug}.jpg`.padEnd(42) + name);
  process.exit(0);
}

let files: string[] = [];
try {
  files = readdirSync(SOURCE).filter((f) => EXTENSIONS.has(extname(f).toLowerCase()));
} catch {
  console.error(`No ${SOURCE}/ folder. Create it and add portraits named like "iype-cherian.jpg".`);
  process.exit(1);
}

mkdirSync(OUT, { recursive: true });

// Scale to cover, then crop centred horizontally and 15% from the top, where faces usually are.
const cover = (w: number, h: number) =>
  `scale=${w}:${h}:force_original_aspect_ratio=increase:flags=lanczos,crop=${w}:${h}:(iw-${w})/2:(ih-${h})*0.15`;

const done: string[] = [];
const unmatched: string[] = [];
for (const file of files) {
  const slug = file.slice(0, -extname(file).length).toLowerCase();
  if (!people.has(slug)) {
    unmatched.push(file);
    continue;
  }
  for (const [suffix, w, h] of [["160", 160, 160], ["600", 480, 600]] as const) {
    const result = spawnSync(
      "ffmpeg",
      ["-loglevel", "error", "-y", "-i", join(SOURCE, file), "-vf", cover(w, h), "-c:v", "libwebp", "-quality", "82", join(OUT, `${slug}-${suffix}.webp`)],
      { stdio: "inherit" },
    );
    if (result.error || result.status !== 0) {
      console.error(`ffmpeg failed on ${file}${result.error ? `: ${result.error.message}` : ""}`);
      process.exit(1);
    }
  }
  done.push(slug);
}

done.sort();
writeFileSync(
  DATA,
  `// GENERATED by \`npm run photos\` (scripts/people-photos.ts). Do not edit by hand.\n` +
    `// Slugs (see src/lib/people.ts) of people with a portrait in public/assets/people/.\n\n` +
    `export const PEOPLE_PHOTOS: ReadonlySet<string> = new Set(${JSON.stringify(done, null, 2)});\n`,
);

console.log(`Converted ${done.length} portrait(s); wrote ${DATA}.`);
if (unmatched.length) {
  console.log(`\nNot matched to anyone (rename to the slug from \`npm run photos -- --list\`):`);
  for (const f of unmatched) console.log(`  ${f}`);
}
const missing = [...people].filter(([slug]) => !done.includes(slug));
if (missing.length) console.log(`\n${missing.length} people still use initials.`);
